/** Words a generated username may end in after the first name ("maya.lifts"). */
export const USERNAME_WORDS = [
  "lifts",
  "trains",
  "squats",
  "pulls",
  "benches",
  "reps",
  "moves",
  "lifting",
  "training",
];

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) => `ARRAY[${xs.map(q).join(", ")}]::text[]`;

function chunked(rows: string[], per = 8): string {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += per) out.push("  " + rows.slice(i, i + per).join(", "));
  return out.join(",\n");
}

function dataSql(): string {
  const firsts: string[] = [];
  for (const style of NAME_STYLES) {
    for (const g of ["f", "m", "u"] as const) {
      for (const n of FIRST_NAMES[style][g]) firsts.push(`(${q(n)}, ${q(style)}, ${q(g)})`);
    }
  }
  const lasts: string[] = [];
  for (const origin of NAME_ORIGINS) {
    for (const n of SURNAMES[origin]) {
      const only = SURNAME_ONLY_GENDER[n];
      lasts.push(`(${q(n)}, ${q(origin)}, ${only ? q(only) : "NULL"})`);
    }
  }
  const origins = NAME_ORIGINS.map(
    (o) =>
      `(${q(o)}, ${ORIGIN_RULES[o].weight}, ${q(JSON.stringify(ORIGIN_RULES[o].pairs))}::jsonb)`,
  );
  const words = (Object.keys(PLACEHOLDER_WORDS) as Array<keyof typeof PLACEHOLDER_WORDS>).flatMap(
    (k) => PLACEHOLDER_WORDS[k].map((w) => `(${q(w)}, ${q(k)})`),
  );
  const blocked = [
    ...PLACEHOLDER_FULL.map((n) => `(${q(n)}, 'stock')`),
    ...Array.from(new Set(WELL_KNOWN.map(foldName))).map((n) => `(${q(n)}, 'well_known')`),
  ];
  return `DELETE FROM public.virtual_name_firsts;
INSERT INTO public.virtual_name_firsts (name, style, gender)
VALUES
${chunked(firsts)};
UPDATE public.virtual_name_firsts SET folded = public.virtual_name_fold(name);

DELETE FROM public.virtual_name_lasts;
INSERT INTO public.virtual_name_lasts (name, origin, only_gender)
VALUES
${chunked(lasts)};
UPDATE public.virtual_name_lasts SET folded = public.virtual_name_fold(name);

DELETE FROM public.virtual_name_origins;
INSERT INTO public.virtual_name_origins (origin, weight, pairs)
VALUES
${chunked(origins, 2)};

DELETE FROM public.virtual_name_words;
INSERT INTO public.virtual_name_words (word, kind)
VALUES
${chunked(words)};

DELETE FROM public.virtual_name_blocked;
INSERT INTO public.virtual_name_blocked (full_name, kind)
VALUES
${chunked(blocked, 4)}
ON CONFLICT (full_name) DO NOTHING;`;
}

