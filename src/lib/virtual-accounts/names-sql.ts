/**
 * Writes 20270602090000_virtual_account_names.sql from name-pool.ts and names.ts:
 *
 *   npx tsx scripts/virtual-names/write-migration.ts
 *
 * Generated, never hand-edited: virtual-account-names.test.ts fails when the file and the
 * definitions disagree. What it puts in the database:
 *
 * - the name pool (first names by style and gender, surnames by origin, which styles go with
 *   which origins), the placeholder words and stock names, and well-known people's names, in
 *   tables nobody but the database's own functions can read;
 * - one generator, virtual_name_generate: a surname by origin (origins the existing virtual
 *   accounts already use come up less), a first name by the styles that origin pairs with and the
 *   gender asked for (else whichever the virtual accounts have fewer of), then refused when it's
 *   a placeholder, alliterative, a well-known person's, a first name or surname another virtual
 *   account has, the same initials as one, or a real member's first name, surname or full name;
 *   a username from the name nobody has;
 * - the checks an admin's own name goes through (virtual_name_problem), a rename that keeps the
 *   account's id, likes and history (admin_virtual_account_rename), a guard that refuses a
 *   placeholder name on any write, and the correction of any virtual account that has one
 *   (virtual_accounts_fix_placeholder_names: run once here and on every like tick).
 */
