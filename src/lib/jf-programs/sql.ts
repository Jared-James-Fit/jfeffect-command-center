import { createHash } from "node:crypto";
import { NEW_EXERCISES } from "./catalog";
import { buildLibrary, type TemplateRow } from "./build";

/** A stable UUID (v5 layout) from a name: how JF_TEMPLATE_IDS were made. */
export function stableUuid(name: string): string {
  const h = createHash("sha1").update(`jf-effect-library:${name}`).digest();
  const b = Buffer.from(h.subarray(0, 16));
  b[6] = (b[6] & 0x0f) | 0x50;
  b[8] = (b[8] & 0x3f) | 0x80;
  const x = b.toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

export const LIBRARY_MIGRATION = "supabase/migrations/20270314090000_jf_effect_program_library.sql";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
/** dollar-quoted, with a tag that can't appear in the text */
function dq(s: string): string {
  const tag = "$jf$";
  if (s.includes(tag)) throw new Error("text contains the dollar-quote tag");
  return `${tag}${s}${tag}`;
}

const NEW = Object.values(NEW_EXERCISES);

/** payload text with each new exercise's fixed id swapped for an existing same-name exercise, when there is one */
function remapped(payloadJson: string): string {
  let expr = dq(payloadJson);
  for (const e of NEW) {
    expr = `replace(${expr}, ${lit(e.id)}, COALESCE((SELECT x.id::text FROM public.exercises x WHERE lower(x.name) = lower(${lit(e.name)}) AND NOT COALESCE(x.archived, false) ORDER BY (x.id = ${lit(e.id)}::uuid) DESC, x.created_at LIMIT 1), ${lit(e.id)}))`;
  }
  return `(${expr})::jsonb`;
}

function exercisesSql(): string {
  const values = NEW.map((e) =>
    `  (${lit(e.id)}::uuid, ${lit(e.name)}, ${lit(e.category)}, ${lit(e.muscle_group)}, ${lit(e.primary_muscle_group)}, ${lit(e.equipment)}, ${lit(e.cues)}, ${lit(e.pattern)})`,
  ).join(",\n");
  return `INSERT INTO public.exercises (id, name, category, muscle_group, primary_muscle_group, equipment, cues, primary_movement_pattern)
SELECT v.id, v.name, v.category, v.muscle_group, v.primary_muscle_group, v.equipment, v.cues, v.pattern
  FROM (VALUES
${values}
  ) AS v(id, name, category, muscle_group, primary_muscle_group, equipment, cues, pattern)
 WHERE NOT EXISTS (SELECT 1 FROM public.exercises e WHERE lower(e.name) = lower(v.name) AND NOT COALESCE(e.archived, false))
ON CONFLICT (id) DO NOTHING;`;
}

export function templateSql(t: TemplateRow): string {
  const tags = `ARRAY[${t.tags.map(lit).join(", ")}]::text[]`;
  return `-- ${t.name}
INSERT INTO public.pl_templates (
  id, name, template_type, training_style, training_focus, tags, status, weeks, days_per_week,
  est_duration_min, goal, description, notes, payload, archived, owner_role, owner_user_id, created_by,
  visibility, payload_revision
)
SELECT ${lit(t.id)}::uuid, ${lit(t.name)}, ${lit(t.template_type)}, ${lit(t.training_style)}, ${lit(t.training_focus)}, ${tags}, ${lit(t.status)}, ${t.weeks}, ${t.days_per_week},
  ${t.est_duration_min}, ${lit(t.goal)}, ${dq(t.description)}, ${dq(t.notes)},
  ${remapped(JSON.stringify(t.payload))},
  false, 'admin', a.uid, a.uid, 'team', 1
  FROM (SELECT (SELECT user_id FROM public.user_roles WHERE role = 'admin' ORDER BY user_id LIMIT 1) AS uid) a
ON CONFLICT (id) DO NOTHING;`;
}

export function librarySql(): string {
  const lib = buildLibrary();
  const header = `-- JF Effect program library: the 12 programs of the JF Effect 12-Program Master
-- Build Specification (Nov 13 2026), as new, unassigned library templates.
--
-- GENERATED by scripts/jf-programs/write-migration.ts from src/lib/jf-programs/
-- (programs.ts holds every prescription and the reason for each change from
-- the spec). Do not edit by hand: src/test/jf-programs.test.ts fails when this
-- file and the definitions disagree.
--
-- Safe to run again: fixed ids (a hash of each slug) with ON CONFLICT DO
-- NOTHING, so a second run adds nothing and never overwrites a coach's edits.
-- Nothing here touches a client's program, logs or any existing template.
--
-- 1. Six zero-equipment exercises the library didn't have (Prone W Raise,
--    Prone Y-T-W Raise, Prone Reverse Snow Angel, Split Squat, Single-Leg Calf
--    Raise, Single-Leg Glute Bridge), each only when no exercise of that name
--    exists; a program then uses whichever exists.
-- 2. The 12 templates: template_type 'block', schema_version 2, three blocks of
--    four weeks, every week written out (144 weeks, 504 core workouts and 12
--    optional ones).
--
-- Rollback: DELETE FROM public.pl_templates WHERE id IN (the 12 ids below)
-- removes them (clients who were assigned one keep their own copy), and the
-- six exercises can be archived from the exercise library.
`;
  return [header, exercisesSql(), ...lib.map(templateSql)].join("\n\n") + "\n";
}
