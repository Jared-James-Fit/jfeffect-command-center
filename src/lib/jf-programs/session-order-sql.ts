const md5 = (s: string) => createHash("md5").update(s, "utf8").digest("hex");

/** Every row's exercise, place and note, block by block (the same text pg_temp.jf_signature builds). */
export function payloadSignature(payload: any): string {
  return md5(
    (payload.blocks_data ?? [])
      .map((b: any) => (b.weeks_data ?? []).map((w: any) => (w.days ?? []).map((d: any) => (d.rows ?? []).map((r: any) => `${r.exercise_id}:${r.sort_order}:${md5(r.notes ?? "")}`).join(",")).join("|")).join(";"))
      .join("#"),
  );
}

/** Each reordered session's exercises in their new order (from the definitions). */
export function sessionOrders(payload: any, titles: string[]): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  const day = (payload.blocks_data?.[0]?.weeks_data?.[0]?.days ?? []) as any[];
  for (const t of titles) {
    const d = day.find((x) => x.title === t);
    if (!d) throw new Error(`no session "${t}"`);
    out[t] = d.rows.map((r: any) => r.exercise_id);
  }
  return out;
}

/** A program's notes as installed on Nov 13 2026: the same text without the Nov 18 session-order change. */
function notesBefore(templateId: string): string {
  const p = JF_PROGRAMS.find((x) => buildLibrary().find((t) => t.slug === x.slug)?.id === templateId);
  if (!p) throw new Error(`no JF program ${templateId}`);
  const changes = p.changes.filter((c) => !c.startsWith("Session order (Nov 18 2026)"));
  return [p.coachGuide, changes.length ? `\nChanges from the JF Effect master spec (Nov 13 2026), and why:\n${changes.map((c) => `- ${c}`).join("\n")}` : ""].join("");
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function sessionOrderSql(): string {
  const lib = new Map(buildLibrary().map((t) => [t.id, t]));
  const parts: string[] = [
    `-- GENERATED by scripts/jf-programs/write-session-order-migration.ts from src/lib/jf-programs (never hand-edited).
-- JF Effect library: sessions reordered for accessory flow (Nov 18 2026), applied to the copies already
-- installed (pl_templates) and published to members (member_plans) only while each is still exactly what
-- was installed; backed up first; checked against the definitions (a mismatch rolls the migration back).
-- Nobody was running any of these programs; the coach's own templates are not touched.

CREATE TABLE IF NOT EXISTS public.template_flow_backup (
  id bigserial PRIMARY KEY,
  batch text NOT NULL,
  template_id uuid NOT NULL,
  plan_id uuid,
  payload jsonb,
  published_payload jsonb,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.template_flow_backup ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.template_flow_backup FROM anon, authenticated;

-- A payload with the named sessions' rows put in the given exercise order (ties keep their order), renumbered.
CREATE OR REPLACE FUNCTION pg_temp.jf_session_order(_payload jsonb, _orders jsonb, _replace jsonb) RETURNS jsonb LANGUAGE sql AS $f$
  SELECT jsonb_set(_payload, '{blocks_data}', coalesce((
    SELECT jsonb_agg(b || jsonb_build_object('weeks_data', coalesce((
      SELECT jsonb_agg(w || jsonb_build_object('days', coalesce((
        SELECT jsonb_agg(CASE WHEN _orders ? (d->>'title') THEN d || jsonb_build_object('rows', (
            SELECT jsonb_agg(x.r || jsonb_build_object('sort_order', x.n - 1, 'notes',
                     CASE WHEN x.r->>'notes' IS NULL THEN NULL
                          ELSE (SELECT coalesce((SELECT replace(x.r->>'notes', p->>0, p->>1) FROM jsonb_array_elements(_replace) p WHERE position(p->>0 in x.r->>'notes') > 0 LIMIT 1), x.r->>'notes')) END)
                   ORDER BY x.n)
              FROM (SELECT r, row_number() OVER (ORDER BY coalesce((SELECT min(o.i) FROM jsonb_array_elements_text(_orders->(d->>'title')) WITH ORDINALITY o(e, i) WHERE o.e = r->>'exercise_id'), 1000), ro) n
                      FROM jsonb_array_elements(d->'rows') WITH ORDINALITY q(r, ro)) x))
          ELSE d END ORDER BY dord)
        FROM jsonb_array_elements(w->'days') WITH ORDINALITY dd(d, dord)), '[]'::jsonb)) ORDER BY word)
      FROM jsonb_array_elements(b->'weeks_data') WITH ORDINALITY ww(w, word)), '[]'::jsonb)) ORDER BY bord)
    FROM jsonb_array_elements(_payload->'blocks_data') WITH ORDINALITY bb(b, bord)), '[]'::jsonb))
$f$;

-- Every row's exercise, place and note (payloadSignature in session-order-sql.ts builds the same).
CREATE OR REPLACE FUNCTION pg_temp.jf_signature(_payload jsonb) RETURNS text LANGUAGE sql AS $f$
  SELECT md5(coalesce((SELECT string_agg(bs, '#' ORDER BY bord) FROM (
    SELECT bord, (SELECT string_agg(ws, ';' ORDER BY word) FROM (
      SELECT word, (SELECT string_agg(ds, '|' ORDER BY dord) FROM (
        SELECT dord, coalesce((SELECT string_agg((r->>'exercise_id') || ':' || (r->>'sort_order') || ':' || md5(coalesce(r->>'notes', '')), ',' ORDER BY ro)
                                 FROM jsonb_array_elements(d->'rows') WITH ORDINALITY q(r, ro)), '') ds
          FROM jsonb_array_elements(w->'days') WITH ORDINALITY dd(d, dord)) x) ws
        FROM jsonb_array_elements(b->'weeks_data') WITH ORDINALITY ww(w, word)) y) bs
      FROM jsonb_array_elements(_payload->'blocks_data') WITH ORDINALITY bb(b, bord)) z), ''))
$f$;
`,
  ];
  for (const c of SESSION_ORDER_CHANGES) {
    const t = lib.get(c.templateId);
    if (!t) throw new Error(`no JF program ${c.templateId}`);
    const orders = sessionOrders(t.payload, c.days);
    const expected = payloadSignature(t.payload);
    const o = q(JSON.stringify(orders));
    // the coach guide as installed (without this change's line), so only the new line is appended
    const before = notesBefore(c.templateId);
    if (!t.notes.startsWith(before)) throw new Error(`notes of ${t.name} don't extend the installed ones`);
    const r = q(JSON.stringify(c.replace ?? []));
    parts.push(`-- ${t.name}: ${c.days.join(", ")}
DO $$
DECLARE _n int;
BEGIN
  -- only a copy still exactly as installed; nothing else, and re-running does nothing
  INSERT INTO public.template_flow_backup (batch, template_id, plan_id, payload, published_payload, notes)
  SELECT 'jf_session_order_2026_11_18', t.id, mp.id, t.payload, mp.published_payload, t.notes
    FROM public.pl_templates t LEFT JOIN public.member_plans mp ON mp.source_template_id = t.id
   WHERE t.id = ${q(c.templateId)} AND md5(t.payload::text) = ${q(c.installedMd5)};
  GET DIAGNOSTICS _n = ROW_COUNT;
  IF _n = 0 THEN RETURN; END IF;
  -- the members' copy only where it is still the installed one too
  UPDATE public.member_plans mp SET published_payload = pg_temp.jf_session_order(mp.published_payload, ${o}::jsonb, ${r}::jsonb),
         published_version = coalesce(mp.published_version, 0) + 1,
         last_published_version = coalesce(t.payload_revision, 0) + 1
    FROM public.pl_templates t
   WHERE mp.source_template_id = t.id AND t.id = ${q(c.templateId)} AND md5(mp.published_payload::text) = ${q(c.installedMd5)};
  UPDATE public.pl_templates SET payload = pg_temp.jf_session_order(payload, ${o}::jsonb, ${r}::jsonb),
         notes = CASE WHEN md5(coalesce(notes, '')) = ${q(md5(before))} THEN notes || ${q(t.notes.slice(before.length))} ELSE notes END,
         payload_revision = coalesce(payload_revision, 0) + 1
   WHERE id = ${q(c.templateId)};
  IF (SELECT pg_temp.jf_signature(payload) FROM public.pl_templates WHERE id = ${q(c.templateId)}) <> ${q(expected)} THEN
    RAISE EXCEPTION 'JF session order: ${t.name.replace(/'/g, "''")} does not match its definition';
  END IF;
  IF EXISTS (SELECT 1 FROM public.member_plans WHERE source_template_id = ${q(c.templateId)}
               AND last_published_version = (SELECT payload_revision FROM public.pl_templates WHERE id = ${q(c.templateId)})
               AND pg_temp.jf_signature(published_payload) <> ${q(expected)}) THEN
    RAISE EXCEPTION 'JF session order: the members'' copy of ${t.name.replace(/'/g, "''")} does not match its definition';
  END IF;
END $$;
`);
  }
  return parts.join("\n");
}
