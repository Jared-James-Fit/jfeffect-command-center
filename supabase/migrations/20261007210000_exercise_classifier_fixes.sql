-- Fine pattern → the coarse vocabulary exercises.primary_movement_pattern allows.
CREATE OR REPLACE FUNCTION public.exercise_coarse_pattern(_pattern text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE
 SET search_path TO 'public'
AS $fn$
  SELECT CASE _pattern WHEN 'squat' THEN 'squat' WHEN 'lunge' THEN 'squat' WHEN 'hinge' THEN 'hip_hinge' WHEN 'back_extension' THEN 'hip_hinge' WHEN 'knee_extension' THEN 'knee_extension' WHEN 'knee_flexion' THEN 'hamstring_curl' WHEN 'hip_thrust' THEN 'glutes' WHEN 'hip_abduction' THEN 'glutes' WHEN 'hip_adduction' THEN 'other' WHEN 'hip_flexion' THEN 'core' WHEN 'calf_raise' THEN 'other' WHEN 'horizontal_press' THEN 'horizontal_push' WHEN 'incline_press' THEN 'horizontal_push' WHEN 'dip' THEN 'horizontal_push' WHEN 'chest_fly' THEN 'horizontal_push' WHEN 'vertical_press' THEN 'vertical_push' WHEN 'horizontal_pull' THEN 'horizontal_pull' WHEN 'vertical_pull' THEN 'vertical_pull' WHEN 'pullover' THEN 'vertical_pull' WHEN 'shrug' THEN 'other' WHEN 'rear_delt' THEN 'delts' WHEN 'lateral_raise' THEN 'delts' WHEN 'front_raise' THEN 'delts' WHEN 'elbow_flexion' THEN 'arms' WHEN 'elbow_extension' THEN 'arms' WHEN 'wrist' THEN 'arms' WHEN 'core_flexion' THEN 'core' WHEN 'core_anti_extension' THEN 'core' WHEN 'core_rotation' THEN 'core' WHEN 'core_lateral' THEN 'core' WHEN 'carry' THEN 'conditioning' WHEN 'olympic' THEN 'conditioning' WHEN 'plyometric' THEN 'conditioning' WHEN 'conditioning' THEN 'conditioning' WHEN 'mobility' THEN 'other' WHEN 'other' THEN 'other' ELSE NULL END
$fn$;

-- Patterns that never build muscle volume.
CREATE OR REPLACE FUNCTION public.exercise_pattern_counts_toward_volume(_pattern text)
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE
 SET search_path TO 'public'
AS $fn$
  SELECT _pattern IS NULL OR _pattern NOT IN ('mobility', 'conditioning')
$fn$;

WITH k AS (
  SELECT x.id, c.pattern, c.primary_muscles, c.secondary_muscles
    FROM public.exercises x, LATERAL public.exercise_classify(x.name, x.category) c
   WHERE x.id IN ('d3ec9e5b-ace7-4092-96a2-f3b531dc01d5','1993fcdd-39e4-4e5f-b187-d6e285a5704d','d4590831-53fc-4790-b578-639f201d8ec9','c40f9039-0c31-425f-b70b-76802a52abbe','ac10db9f-a07c-4df1-9b09-bf1b9eaf30e5','2d472b54-522a-4a71-9551-6f0cf35720e7','49772aaa-986d-4b0f-95a0-e625637ad449','781a6922-0e65-44c4-a167-1cb48cc1b216','1bf2614c-81b4-4441-a1fb-7fdb35244cc2','53ef969b-493c-44e5-994d-43b8e9b6b6b2','60b8c727-a1c7-4faa-b726-88e9322a8c33')
     AND c.matched AND public.exercise_pattern_counts_toward_volume(c.pattern)
)
UPDATE public.exercises e SET
  muscle_groups = k.primary_muscles,
  secondary_muscle_groups = k.secondary_muscles,
  primary_movement_pattern = public.exercise_coarse_pattern(k.pattern),
  counts_toward_volume = true,
  primary_muscle_group = public.muscle_label_from_key(k.primary_muscles[1]),
  muscle_group = (SELECT string_agg(public.muscle_label_from_key(m), ', ' ORDER BY o)
                    FROM unnest(k.primary_muscles) WITH ORDINALITY AS u(m, o))
FROM k
WHERE e.id = k.id;
