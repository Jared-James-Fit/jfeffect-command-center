  n text := ' ' || btrim(regexp_replace(lower(coalesce(_name, '')), '[^a-z0-9]+', ' ', 'g')) || ' ';
  c text := lower(coalesce(_category, ''));
  p text;
  pm text[];
  sm text[];
  eq text;
BEGIN
  eq := CASE
      WHEN n ~ ' smith ' THEN 'Smith Machine'
      WHEN n ~ ' (barbell|bb|ez bar|ez|trap bar|hex bar|safety bar|ssb|landmine|axle|cambered|swiss bar|football bar) ' THEN 'Barbell'
      WHEN n ~ ' (dumbbell|dumbbells|db) ' THEN 'Dumbbell'
      WHEN n ~ ' (kettlebell|kettlebells|kb) ' THEN 'Kettlebell'
      WHEN n ~ ' (cable|cables|rope|pulldown|pull down|lat pull|pushdown|push down|crossover) ' THEN 'Cable'
      WHEN n ~ ' (band|bands|banded|resistance band|mini band) ' THEN 'Bands'
      WHEN n ~ ' (machine|hammer strength|leg press|hack squat|pendulum|belt squat|pec deck|selectorized|plate loaded|seated row machine|chest supported row machine|multi hip|glute ham|ghd|reverse hyper|leg extension|leg curl) ' THEN 'Machine'
      WHEN n ~ ' (push up|pushup|pull up|pullup|chin up|chinup|dip|dips|plank|bodyweight|bw|air squat|inverted row|nordic|sit up|situp|crunch|burpee|jump|hollow|l sit|muscle up|pistol) ' THEN 'Bodyweight'
    END;
  IF n ~ 'stretch|mobility|yoga|pose|foam roll|smr|lacrosse ball|release|cat cow|90 90|world s greatest|thread the needle|circles|dislocat| cars |basic toe touch|standing toe touch|forward fold' THEN
