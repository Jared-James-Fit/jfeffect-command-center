    p := 'hip_adduction'; pm := ARRAY['adductors']::text[]; sm := ARRAY['core']::text[];
  ELSIF n ~ ' (abduction|abductor|abductors|clamshell|clam shell|clams?|fire hydrants?|monster walks?|lateral band walks?|band walks?|crab walks?|side lying leg (raise|lift)s?|side lying hip raises?|standing side leg raises?|side kicks?) ' AND n !~ ' (shoulder|arm) (abduction|abductor) ' THEN
