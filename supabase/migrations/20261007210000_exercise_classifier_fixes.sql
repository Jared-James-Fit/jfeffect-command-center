  ELSIF n ~ ' (row|rows|seal row|pendlay|meadows|kroc|t bar|renegade) ' THEN
    p := 'horizontal_pull'; pm := ARRAY['upper_back', 'lats']::text[]; sm := ARRAY['rear_delts', 'biceps']::text[];
