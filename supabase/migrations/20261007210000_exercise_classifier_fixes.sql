  ELSIF n ~ ' (hip flexion|hip flexor march|psoas march) ' THEN
    p := 'hip_flexion'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (glute kick ?backs?|kickback glute|donkey kicks?|donkey kickbacks?|(straight |bent )?leg kickbacks?|hip kickbacks?|glute medius kickback|hip extension|glute extension|cable kickback|reverse lunge kickback|quadruped kickback|rear kicks?) ' AND n !~ ' (pullover|tricep|triceps) ' THEN
    p := 'hip_thrust'; pm := ARRAY['glutes']::text[]; sm := ARRAY['hamstrings']::text[];
  ELSIF n ~ ' ((external|internal) (shoulder )?rotation?|rotator|cuban|no money) ' THEN
    p := 'rear_delt'; pm := ARRAY['rear_delts']::text[]; sm := ARRAY['upper_back']::text[];
  ELSIF n ~ ' (upward rotation|scapular elevation) ' THEN
    p := 'shrug'; pm := ARRAY['traps']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (scap|scapula|scapular) (retraction|retractions|squeeze|squeezes) ' THEN
    p := 'horizontal_pull'; pm := ARRAY['upper_back']::text[]; sm := ARRAY['traps']::text[];
  ELSIF n ~ ' (wrist curl|wrist extension|reverse wrist|wrist roller|pronation|supination|palm up palm down|gripper|grip trainer|grip strength|hand grip|dead hang|plate pinch|farmer s hold) ' THEN
    p := 'wrist'; pm := ARRAY['forearms']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (calf|calves|calve|heel raises?|donkey raises?|tibialis|tib raises?|toe raises?|plantar flexion|dorsal flexion) ' THEN
    p := 'calf_raise'; pm := ARRAY['calves']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (mountain climber) ' THEN
    p := 'core_flexion'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (nordic|glute ham raise|ghr|leg curl|hamstring curl|lying curl|seated curl machine|slider curl|stability ball curl|swiss ball leg curl|ball leg curl) ' THEN
    p := 'knee_flexion'; pm := ARRAY['hamstrings']::text[]; sm := ARRAY['calves']::text[];
  ELSIF n ~ ' (hip thrusts?|hip thrusters?|glute bridges?|frog pumps?|kas glute|glute drive|bridge) ' THEN
    p := 'hip_thrust'; pm := ARRAY['glutes']::text[]; sm := ARRAY['hamstrings']::text[];
  ELSIF n ~ ' (romanian|rdl|stiff leg|stiff legged|sldl|good mornings?|single leg deadlift|b stance deadlift|kickstand deadlift) ' THEN
    p := 'hinge'; pm := ARRAY['hamstrings', 'glutes']::text[]; sm := ARRAY['lower_back', 'forearms']::text[];
  ELSIF n ~ ' (back extension|hyperextension|hyper extension|reverse hyper|45 degree (back|hyper|glute)|superman|bird dog) ' THEN
    p := 'back_extension'; pm := ARRAY['lower_back', 'glutes']::text[]; sm := ARRAY['hamstrings']::text[];
  ELSIF n ~ ' (kettlebell swings?|kb swings?|dumbbell swings?|pull ?throughs?) ' THEN
    p := 'hinge'; pm := ARRAY['glutes', 'hamstrings']::text[]; sm := ARRAY['lower_back', 'core']::text[];
  ELSIF n ~ ' (trap bar deadlift|hex bar deadlift|trap bar pull) ' THEN
    p := 'hinge'; pm := ARRAY['quads', 'glutes', 'hamstrings']::text[]; sm := ARRAY['lower_back', 'traps', 'forearms']::text[];
  ELSIF n ~ ' (deadlifts?|rack pulls?|block pulls?|deficit pulls?) ' THEN
    p := 'hinge'; pm := ARRAY['glutes', 'hamstrings', 'lower_back']::text[]; sm := ARRAY['quads', 'upper_back', 'traps', 'forearms', 'adductors']::text[];
  ELSIF n ~ ' (leg extension|knee extension|sissy squat|reverse nordic|spanish squat|terminal knee) ' THEN
    p := 'knee_extension'; pm := ARRAY['quads']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (bench dip|chair dip|triceps dip|tricep dip|dip on floor|between chairs|floor dip|couch) ' THEN
    p := 'dip'; pm := ARRAY['triceps']::text[]; sm := ARRAY['chest', 'front_delts']::text[];
  ELSIF n ~ ' (reverse curl|hammer curl|zottman) ' THEN
    p := 'elbow_flexion'; pm := ARRAY['biceps', 'forearms']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (curl|curls) ' THEN
    p := 'elbow_flexion'; pm := ARRAY['biceps']::text[]; sm := ARRAY['forearms']::text[];
  ELSIF n ~ ' (jm press|close grip bench|close grip press|cg bench|close grip floor press|close grip push up|diamond push up|tate press) ' THEN
    p := 'horizontal_press'; pm := ARRAY['triceps', 'chest']::text[]; sm := ARRAY['front_delts']::text[];
  ELSIF n ~ ' (tricep|triceps|pushdown|push down|skull crusher|skullcrusher|kickback|french press|overhead extension|lying extension|elbow extension) ' AND n !~ ' straight arm ' THEN
    p := 'elbow_extension'; pm := ARRAY['triceps']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (face ?pulls?|rear delt|rear deltoid|reverse fly|reverse flye|reverse machine fly|reverse cable fly|reverse dumbbell fly|rear fly|rear lateral|reverse pec deck|band pull apart|pull apart|bent over fly|bent over raise|bent over lateral|prone t|t raise|w raise|breeding) ' THEN
    p := 'rear_delt'; pm := ARRAY['rear_delts']::text[]; sm := ARRAY['upper_back']::text[];
  ELSIF n ~ ' (upright rows?) ' THEN
    p := 'lateral_raise'; pm := ARRAY['side_delts', 'traps']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (lateral raises?|side raises?|lat raises?|lateral delt|lu raises?|shoulder abduction|iron cross|y raises?|prone y|side lying one hand raise) ' THEN
    p := 'lateral_raise'; pm := ARRAY['side_delts']::text[]; sm := ARRAY['traps']::text[];
  ELSIF n ~ ' (front raises?|plate raises?|shoulder flexion|alternate raises?|vertical front raises?|cross raises?) ' THEN
    p := 'front_raise'; pm := ARRAY['front_delts']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (shrug|shrugs) ' THEN
    p := 'shrug'; pm := ARRAY['traps']::text[]; sm := ARRAY['forearms']::text[];
  ELSIF n ~ ' (wall sit|lunge|lunges|split squat|bulgarian|step up|stepup|step ups|step down|curtsy|pistol|skater squat|single leg squat|rear foot elevated|rfess) ' THEN
    p := 'lunge'; pm := ARRAY['quads', 'glutes']::text[]; sm := ARRAY['adductors', 'hamstrings']::text[];
  ELSIF n ~ ' (thrusters?) ' THEN
    p := 'squat'; pm := ARRAY['quads', 'glutes', 'front_delts']::text[]; sm := ARRAY['triceps', 'core']::text[];
  ELSIF n ~ ' (leg press|hack squat|pendulum squat|belt squat|v squat) ' THEN
    p := 'squat'; pm := ARRAY['quads', 'glutes']::text[]; sm := ARRAY['adductors']::text[];
  ELSIF n ~ ' (front squat|goblet squat|zercher|cyclist squat|heel elevated squat|high bar|highbar) ' THEN
    p := 'squat'; pm := ARRAY['quads', 'glutes']::text[]; sm := ARRAY['adductors', 'upper_back', 'core']::text[];
  ELSIF n ~ ' (squat|squats) ' THEN
    p := 'squat'; pm := ARRAY['quads', 'glutes', 'adductors']::text[]; sm := ARRAY['lower_back', 'core']::text[];
  ELSIF n ~ ' (pullover|pull over|straight arm pulldown|straight arm pull down|straight arm pushdown|straight arm push down|pushdown straight arm|push down straight arm|lat prayer|shoulder adduction|shoulder extension) ' THEN
