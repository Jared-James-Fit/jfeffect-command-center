-- Classifier fixes found by running real swap lists against the library:
--  * "Shoulder Abduction" / "Shoulder Adduction" are lateral-raise / lat work,
--    not hip abduction (glutes) / hip adduction (adductors).
--  * Glute kickbacks ("Cable Straight-Leg Kickback", "Cable Donkey Kickback",
--    band leg kickbacks) were counted as triceps; a "Tricep Cable Kickback" as glutes.
--  * "Cable Pushdown (Straight Arm)" is a lat movement, not triceps.
--  * Scapular retractions are upper-back work (were untagged).
-- Regenerated exercise_classify() from src/lib/exercise-classifier.ts, then the
-- 11 affected library rows are re-tagged by that same function.

-- GENERATED by exerciseClassifierSql() in src/lib/exercise-classifier-sql.ts — do not hand-edit.
CREATE OR REPLACE FUNCTION public.exercise_classify(_name text, _category text DEFAULT NULL)
