    p := 'conditioning'; pm := ARRAY['other']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (clean|snatch|jerk|high pull) ' AND n !~ ' (grip deadlift|snatch deadlift|clean deadlift) ' THEN
    p := 'olympic'; pm := ARRAY['quads', 'glutes', 'traps']::text[]; sm := ARRAY['hamstrings', 'upper_back', 'calves']::text[];
  ELSIF n ~ ' (clap push|plyo push|plyometric push) ' THEN
    p := 'horizontal_press'; pm := ARRAY['chest', 'triceps']::text[]; sm := ARRAY['front_delts']::text[];
  ELSIF n ~ ' (box jump|broad jump|depth jump|jump squat|squat jump|tuck jump|bound|bounding|pogo|plyo|med ball throw|medicine ball throw|lateral hop|skater jump) ' THEN
    p := 'plyometric'; pm := ARRAY['quads', 'glutes']::text[]; sm := ARRAY['calves']::text[];
