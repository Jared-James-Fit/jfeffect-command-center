  ELSIF n ~ ' (overhead press|ohp|military press|shoulder press|shoulders press|shoulder pres|push press|strict press|arnold press|landmine press|landmine alternating single arm press|z press|seated press|seated alternate press|alternate side press|palms in press|scott press|w press|y press|seesaw press|behind neck press|anti gravity press|press under|viking press|pike push ups?|handstand push|hspu) ' THEN
    p := 'vertical_press'; pm := ARRAY['front_delts']::text[]; sm := ARRAY['triceps', 'side_delts']::text[];
  ELSIF n ~ ' incline ' AND n ~ '(press|push up|pushup)' THEN
    p := 'incline_press'; pm := ARRAY['chest', 'front_delts']::text[]; sm := ARRAY['triceps']::text[];
  ELSIF n ~ ' (bench press|competition bench|dead bench|paused? bench|flat bench|touch and go bench|floor press|spoto|spotto|larsen|pin press|board press|chest press|push up|pushup|push ups|pushups|press up|svend|plate press|squeeze press|hex press|decline press|decline hammer press|decline one arm hammer press|decline bench|close neutral grip press|dumbbell press|db press|machine press|band press) ' THEN
    p := 'horizontal_press'; pm := ARRAY['chest', 'triceps']::text[]; sm := ARRAY['front_delts']::text[];
  ELSIF n ~ ' (farmer|farmers|suitcase carry|carry|carries|yoke) ' THEN
    p := 'carry'; pm := ARRAY['forearms', 'traps', 'core']::text[]; sm := ARRAY['glutes']::text[];
  ELSIF n ~ ' (side plank|side bends?|oblique|windmill) ' THEN
    p := 'core_lateral'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (plank|ab wheel|rollout|roll out|dead bug|deadbug|hollow|body saw|stir the pot|bear hold|l sit) ' THEN
    p := 'core_anti_extension'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (pallof|palloff|woodchop|wood chop|wood choppers?|diagonal chop|chop|russian twist|rotation|rotational|twist|twisting|landmine 180|anti rotation) ' THEN
    p := 'core_rotation'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (front lever|back lever|dragon flag) ' THEN
    p := 'core_anti_extension'; pm := ARRAY['core', 'lats']::text[]; sm := '{}'::text[];
  ELSIF n ~ ' (turkish get ?up|tgu) ' THEN
    p := 'core_lateral'; pm := ARRAY['core', 'front_delts']::text[]; sm := ARRAY['glutes']::text[];
  ELSIF n ~ ' (handstand hold|hand stand hold) ' THEN
    p := 'vertical_press'; pm := ARRAY['front_delts']::text[]; sm := ARRAY['triceps', 'core']::text[];
  ELSIF n ~ ' (crunch|crunches|sit up|situp|sit ups|situps|leg raises?|knee raises?|toes to bar|v up|vup|flutter|scissors?|toe touch|toe touches|jackknife|jack knives|hanging raise|mountain climbers?|heel touch|heel touches|knee tucks?|bicycles?|wind wipers|dragonfly|leg lifts?|toe taps?|abs|ab) ' THEN
    p := 'core_flexion'; pm := ARRAY['core']::text[]; sm := '{}'::text[];
  ELSIF position('stretch' in c) > 0 OR c = 'yoga' THEN
    RETURN QUERY SELECT 'mobility'::text, ARRAY['other']::text[], '{}'::text[], NULL::text, true;
    RETURN;
  ELSE
    RETURN QUERY SELECT 'other'::text, ARRAY['other']::text[], '{}'::text[], eq, false;
    RETURN;
  END IF;
  IF p = 'horizontal_pull' AND n ~ 'wide' THEN
    pm := ARRAY['upper_back', 'rear_delts']::text[]; sm := ARRAY['biceps']::text[];
  ELSIF p = 'horizontal_pull' AND n ~ '(lat focus|lat row|kayak|single arm|one arm|1 arm)' THEN
    pm := ARRAY['lats', 'upper_back']::text[]; sm := ARRAY['biceps', 'rear_delts']::text[];
  ELSIF p = 'vertical_pull' AND n ~ '(chin|underhand|supinated)' THEN
    sm := ARRAY['biceps', 'upper_back']::text[];
  ELSIF p = 'squat' AND n ~ '(sumo|wide stance|plie)' THEN
    pm := ARRAY['quads', 'glutes', 'adductors']::text[];
  ELSIF p = 'hinge' AND n ~ '(sumo)' AND n !~ '(romanian|rdl|stiff)' THEN
    pm := ARRAY['glutes', 'quads', 'adductors']::text[]; sm := ARRAY['hamstrings', 'lower_back', 'upper_back', 'forearms']::text[];
  ELSIF p = 'horizontal_press' AND n ~ '(wide grip)' THEN
    pm := ARRAY['chest']::text[]; sm := ARRAY['front_delts', 'triceps']::text[];
  ELSIF p = 'lunge' AND n ~ '(lateral lunge|side lunge|cossack)' THEN
    pm := ARRAY['adductors', 'quads', 'glutes']::text[]; sm := '{}'::text[];
  END IF;
  sm := ARRAY(SELECT m FROM unnest(sm) WITH ORDINALITY AS u(m, o) WHERE m <> ALL (pm) ORDER BY o);
  IF p = 'mobility' AND eq IS DISTINCT FROM 'Bands' THEN eq := NULL; END IF;
  RETURN QUERY SELECT p, pm, sm, eq, true;
END
