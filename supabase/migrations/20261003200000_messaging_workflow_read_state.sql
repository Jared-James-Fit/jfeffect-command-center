-- Messaging: three independent concepts.
--   1. COACH UNREAD      per staff member: has *this* coach seen the client's new inbound activity?
--   2. CLIENT READ       messages.read_by_client_at (set only when the client views the conversation)
--   3. COACH WORKFLOW    conversation_state.workflow_status: needs_response | waiting_on_client | done
-- Unread never changes workflow; workflow never changes unread.

-- ---------------------------------------------------------------------------
-- Automated outbound messages (check-in / nutrition reminders) are flagged so
-- they never look like the coach's own work and never create coach attention.
-- ---------------------------------------------------------------------------
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_automated boolean NOT NULL DEFAULT false;

CREATE OR REPLACE FUNCTION public.message_attachment_kinds(_attachments jsonb)
RETURNS text[] LANGUAGE sql IMMUTABLE SET search_path = public AS $$
  SELECT coalesce(array_agg(a->>'kind') FILTER (WHERE a->>'kind' IS NOT NULL), '{}')
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(_attachments) = 'array' THEN _attachments ELSE '[]'::jsonb END) a
$$;

CREATE OR REPLACE FUNCTION public.tg_messages_flag_automated()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NEW.sender_role = 'admin'
     AND 'checkin_request' = ANY(public.message_attachment_kinds(NEW.attachments))
     AND coalesce(NEW.body,'') ~* '^quick (60-second weekly|monthly nutrition) check-in' THEN
    NEW.is_automated := true;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_messages_flag_automated ON public.messages;
CREATE TRIGGER trg_messages_flag_automated BEFORE INSERT ON public.messages
FOR EACH ROW EXECUTE FUNCTION public.tg_messages_flag_automated();

UPDATE public.messages SET is_automated = true
 WHERE NOT is_automated AND sender_role = 'admin'
   AND 'checkin_request' = ANY(public.message_attachment_kinds(attachments))
   AND coalesce(body,'') ~* '^quick (60-second weekly|monthly nutrition) check-in';

