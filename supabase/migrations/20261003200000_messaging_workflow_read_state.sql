-- ---------------------------------------------------------------------------
-- Backfill (no fabricated read receipts: read_by_client_at is left as recorded).
-- ---------------------------------------------------------------------------
INSERT INTO public.conversation_state (client_id)
SELECT DISTINCT m.client_id FROM public.messages m
 WHERE NOT EXISTS (SELECT 1 FROM public.conversation_state s WHERE s.client_id = m.client_id)
ON CONFLICT DO NOTHING;

WITH inbound AS (
  SELECT client_id, max(at) at FROM (
    SELECT client_id, created_at at FROM public.messages WHERE sender_role = 'client' AND NOT is_internal_note
    UNION ALL SELECT client_id, submitted_at FROM public.nf_submissions WHERE submitted_at IS NOT NULL AND client_id IS NOT NULL
  ) x GROUP BY 1
), last_msg AS (
  SELECT DISTINCT ON (client_id) client_id, sender_role, is_automated, created_at
    FROM public.messages
   WHERE NOT is_internal_note AND coalesce(delivery_status, 'sent') IN ('sent', 'sending')
   ORDER BY client_id, created_at DESC
), last_human AS (
  SELECT DISTINCT ON (client_id) client_id, sender_role, created_at
    FROM public.messages
   WHERE NOT is_internal_note AND NOT is_automated AND coalesce(delivery_status, 'sent') IN ('sent', 'sending')
   ORDER BY client_id, created_at DESC
), pending_form AS (
  SELECT f.client_id, max(f.submitted_at) at FROM public.nf_submissions f
   WHERE f.submitted_at IS NOT NULL AND f.reviewed_at IS NULL AND f.client_id IS NOT NULL GROUP BY 1
)
UPDATE public.conversation_state s SET
  last_inbound_at = i.at,
  workflow_status = CASE
    WHEN s.status = 'resolved' THEN 'done'
    WHEN lh.sender_role = 'client' THEN 'needs_response'
    WHEN pf.at IS NOT NULL AND pf.at > coalesce((SELECT max(created_at) FROM public.messages m WHERE m.client_id = s.client_id AND m.sender_role = 'admin' AND NOT m.is_automated AND NOT m.is_internal_note), '-infinity') THEN 'needs_response'
    WHEN lm.sender_role = 'admin' THEN 'waiting_on_client'
    ELSE 'done' END,
  workflow_reason = 'backfill',
  workflow_status_updated_at = coalesce(lm.created_at, s.updated_at),
  priority = CASE WHEN s.priority = 'Needs Response' THEN 'Normal' ELSE s.priority END
FROM public.conversation_state s2
LEFT JOIN inbound i ON i.client_id = s2.client_id
LEFT JOIN last_msg lm ON lm.client_id = s2.client_id
LEFT JOIN last_human lh ON lh.client_id = s2.client_id
LEFT JOIN pending_form pf ON pf.client_id = s2.client_id
WHERE s.client_id = s2.client_id AND s.workflow_reason IS NULL;

-- Existing global read position becomes every current staff member's own starting point.
INSERT INTO public.conversation_staff_reads (client_id, user_id, last_read_at)
SELECT s.client_id, ur.user_id, s.admin_last_read_at
  FROM public.conversation_state s
  JOIN public.user_roles ur ON ur.role IN ('admin', 'coach')
 WHERE s.admin_last_read_at IS NOT NULL
ON CONFLICT DO NOTHING;
