-- Single writer for workflow changes. Records history only when the status changes.
CREATE OR REPLACE FUNCTION public.apply_conversation_workflow(
  _client_id uuid, _status text, _reason text, _actor uuid, _message_id uuid DEFAULT NULL,
  _only_if_not_needs_response boolean DEFAULT false, _at timestamptz DEFAULT now())
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE cur text;
BEGIN
  INSERT INTO public.conversation_state (client_id, workflow_status, workflow_status_updated_at, workflow_status_updated_by, workflow_reason)
  VALUES (_client_id, _status, _at, _actor, _reason)
  ON CONFLICT (client_id) DO NOTHING
  RETURNING NULL INTO cur;
  IF FOUND THEN
    INSERT INTO public.conversation_workflow_events (client_id, workflow_status, reason, actor_id, message_id, created_at)
    VALUES (_client_id, _status, _reason, _actor, _message_id, _at);
    RETURN;
  END IF;
  SELECT workflow_status INTO cur FROM public.conversation_state WHERE client_id = _client_id FOR UPDATE;
  IF _only_if_not_needs_response AND cur = 'needs_response' THEN RETURN; END IF;
  IF cur IS DISTINCT FROM _status THEN
    UPDATE public.conversation_state
       SET workflow_status = _status, workflow_status_updated_at = _at,
           workflow_status_updated_by = _actor, workflow_reason = _reason, updated_at = now()
     WHERE client_id = _client_id;
    INSERT INTO public.conversation_workflow_events (client_id, workflow_status, reason, actor_id, message_id, created_at)
    VALUES (_client_id, _status, _reason, _actor, _message_id, _at);
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.apply_conversation_workflow(uuid, text, text, uuid, uuid, boolean, timestamptz) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.note_inbound_activity(_client_id uuid, _kind text, _at timestamptz)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.conversation_state (client_id, last_inbound_at, last_inbound_kind)
  VALUES (_client_id, _at, _kind)
  ON CONFLICT (client_id) DO UPDATE
    SET last_inbound_at = GREATEST(coalesce(public.conversation_state.last_inbound_at, EXCLUDED.last_inbound_at), EXCLUDED.last_inbound_at),
        last_inbound_kind = CASE WHEN public.conversation_state.last_inbound_at IS NULL
                                   OR EXCLUDED.last_inbound_at >= public.conversation_state.last_inbound_at
                                 THEN EXCLUDED.last_inbound_kind ELSE public.conversation_state.last_inbound_kind END,
        updated_at = now();
END;
$$;
REVOKE ALL ON FUNCTION public.note_inbound_activity(uuid, text, timestamptz) FROM PUBLIC, anon, authenticated;

-- Messages drive the workflow:
--   client message / check-in submission → NEEDS RESPONSE (+ inbound activity)
--   coach reply                           → WAITING ON CLIENT
--   automated reminder / request card     → WAITING ON CLIENT, but never clears an open NEEDS RESPONSE
CREATE OR REPLACE FUNCTION public.tg_messages_workflow()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE kinds text[];
BEGIN
  IF NEW.is_internal_note OR coalesce(NEW.delivery_status, 'sent') NOT IN ('sent', 'sending') THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' AND coalesce(OLD.delivery_status, 'sent') IN ('sent', 'sending') THEN RETURN NEW; END IF;
  kinds := public.message_attachment_kinds(NEW.attachments);
  IF NEW.sender_role = 'client' THEN
    PERFORM public.note_inbound_activity(NEW.client_id,
      CASE WHEN 'checkin_submission' = ANY(kinds) THEN 'checkin' ELSE 'message' END, NEW.created_at);
    PERFORM public.apply_conversation_workflow(NEW.client_id, 'needs_response',
      CASE WHEN 'checkin_submission' = ANY(kinds) THEN 'checkin_submitted' ELSE 'client_message' END,
      NEW.sender_id, NEW.id, false, NEW.created_at);
  ELSIF NEW.is_automated OR kinds && ARRAY['checkin_request','form_request','signature_request'] THEN
    PERFORM public.apply_conversation_workflow(NEW.client_id, 'waiting_on_client',
      CASE WHEN NEW.is_automated THEN 'automated_request' ELSE 'request_sent' END,
      CASE WHEN NEW.is_automated THEN NULL ELSE NEW.sender_id END, NEW.id, true, NEW.created_at);
  ELSE
    PERFORM public.apply_conversation_workflow(NEW.client_id, 'waiting_on_client', 'coach_replied',
      NEW.sender_id, NEW.id, false, NEW.created_at);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_messages_workflow ON public.messages;
CREATE TRIGGER trg_messages_workflow AFTER INSERT OR UPDATE OF delivery_status ON public.messages
FOR EACH ROW EXECUTE FUNCTION public.tg_messages_workflow();

-- Native form submissions and lift uploads are inbound client activity too.
CREATE OR REPLACE FUNCTION public.tg_nf_submissions_workflow()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.client_id IS NULL OR NEW.submitted_at IS NULL THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' AND OLD.submitted_at IS NOT DISTINCT FROM NEW.submitted_at THEN RETURN NEW; END IF;
  PERFORM public.note_inbound_activity(NEW.client_id, 'form', NEW.submitted_at);
  PERFORM public.apply_conversation_workflow(NEW.client_id, 'needs_response', 'form_submitted', NULL, NULL, false, NEW.submitted_at);
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_nf_submissions_workflow ON public.nf_submissions;
CREATE TRIGGER trg_nf_submissions_workflow AFTER INSERT OR UPDATE OF submitted_at ON public.nf_submissions
FOR EACH ROW EXECUTE FUNCTION public.tg_nf_submissions_workflow();

CREATE OR REPLACE FUNCTION public.tg_lift_videos_workflow()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.client_id IS NULL OR coalesce(NEW.archived, false) THEN RETURN NEW; END IF;
  PERFORM public.note_inbound_activity(NEW.client_id, 'lift_video', NEW.created_at);
  PERFORM public.apply_conversation_workflow(NEW.client_id, 'needs_response', 'lift_video_uploaded', NULL, NULL, false, NEW.created_at);
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_lift_videos_workflow ON public.lift_videos;
CREATE TRIGGER trg_lift_videos_workflow AFTER INSERT ON public.lift_videos
FOR EACH ROW EXECUTE FUNCTION public.tg_lift_videos_workflow();

-- ---------------------------------------------------------------------------
-- Per-staff read state (coach A reading does not clear coach B's dot).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.conversation_staff_reads (
  client_id uuid NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
  user_id uuid NOT NULL,
  last_read_at timestamptz,
  manual_unread boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (client_id, user_id)
);
ALTER TABLE public.conversation_staff_reads ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Staff read own read state" ON public.conversation_staff_reads;
CREATE POLICY "Staff read own read state" ON public.conversation_staff_reads FOR SELECT TO authenticated
  USING (user_id = auth.uid());

CREATE OR REPLACE FUNCTION public.can_staff_conversation(_client_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.has_role(auth.uid(), 'admin') OR public.is_assigned_coach(_client_id)
$$;

CREATE OR REPLACE FUNCTION public.staff_mark_conversation_read(_client_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.can_staff_conversation(_client_id) THEN RAISE EXCEPTION 'Not allowed' USING ERRCODE = '42501'; END IF;
  INSERT INTO public.conversation_staff_reads (client_id, user_id, last_read_at, manual_unread, updated_at)
  VALUES (_client_id, auth.uid(), now(), false, now())
  ON CONFLICT (client_id, user_id) DO UPDATE SET last_read_at = now(), manual_unread = false, updated_at = now();
END;
$$;
GRANT EXECUTE ON FUNCTION public.staff_mark_conversation_read(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.staff_mark_conversation_unread(_client_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.can_staff_conversation(_client_id) THEN RAISE EXCEPTION 'Not allowed' USING ERRCODE = '42501'; END IF;
  INSERT INTO public.conversation_staff_reads (client_id, user_id, manual_unread, updated_at)
  VALUES (_client_id, auth.uid(), true, now())
  ON CONFLICT (client_id, user_id) DO UPDATE SET manual_unread = true, updated_at = now();
END;
$$;
GRANT EXECUTE ON FUNCTION public.staff_mark_conversation_unread(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.set_conversation_workflow(_client_id uuid, _status text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.can_staff_conversation(_client_id) THEN RAISE EXCEPTION 'Not allowed' USING ERRCODE = '42501'; END IF;
  IF _status NOT IN ('needs_response','waiting_on_client','done') THEN RAISE EXCEPTION 'Unknown status %', _status; END IF;
  PERFORM public.apply_conversation_workflow(_client_id, _status, 'manual', auth.uid(), NULL, false, now());
  -- A manual decision is always recorded, even if the status didn't change.
  UPDATE public.conversation_state SET workflow_status_updated_at = now(), workflow_status_updated_by = auth.uid(), workflow_reason = 'manual'
   WHERE client_id = _client_id;
END;
$$;
GRANT EXECUTE ON FUNCTION public.set_conversation_workflow(uuid, text) TO authenticated;

-- Everything the inbox, filter counts and nav badge need, for the calling staff member.
CREATE OR REPLACE FUNCTION public.staff_inbox_state()
RETURNS TABLE(client_id uuid, workflow_status text, workflow_reason text, workflow_status_updated_at timestamptz,
              workflow_updated_by_name text, last_inbound_at timestamptz, last_inbound_kind text,
              my_last_read_at timestamptz, unread boolean, unread_count int, archived boolean)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE me uuid := auth.uid(); is_admin boolean;
BEGIN
  IF me IS NULL THEN RAISE EXCEPTION 'Not allowed' USING ERRCODE = '42501'; END IF;
  is_admin := public.has_role(me, 'admin');
  IF NOT is_admin AND NOT public.has_role(me, 'coach') THEN RAISE EXCEPTION 'Not allowed' USING ERRCODE = '42501'; END IF;
  RETURN QUERY
  WITH cs AS (
    SELECT s.*, coalesce(r.last_read_at, s.admin_last_read_at) AS read_at, coalesce(r.manual_unread, false) AS manual
      FROM public.conversation_state s
      LEFT JOIN public.conversation_staff_reads r ON r.client_id = s.client_id AND r.user_id = me
     WHERE is_admin OR public.is_assigned_coach(s.client_id)
  )
  SELECT cs.client_id, cs.workflow_status, cs.workflow_reason, cs.workflow_status_updated_at,
         (SELECT coalesce(nullif(btrim(coalesce(p.full_name, '')), ''), 'Coach') FROM public.coaches p WHERE p.user_id = cs.workflow_status_updated_by LIMIT 1),
         cs.last_inbound_at, cs.last_inbound_kind, cs.read_at,
         cs.manual OR (cs.last_inbound_at IS NOT NULL AND cs.last_inbound_at > coalesce(cs.read_at, '-infinity'::timestamptz)),
         GREATEST(
           (SELECT count(*)::int FROM public.messages m
             WHERE m.client_id = cs.client_id AND m.sender_role = 'client' AND NOT m.is_internal_note
               AND m.created_at > coalesce(cs.read_at, '-infinity'::timestamptz)),
           CASE WHEN cs.manual OR (cs.last_inbound_at > coalesce(cs.read_at, '-infinity'::timestamptz)) THEN 1 ELSE 0 END),
         cs.status = 'archived'
    FROM cs;
END;
$$;
GRANT EXECUTE ON FUNCTION public.staff_inbox_state() TO authenticated;

