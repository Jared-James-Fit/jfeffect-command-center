// Generates src/styles/dark-palette.css — dark-mode equivalents for the
// hard-coded Tailwind palette shades used across the app (pastel tints like
// bg-amber-50, deep text like text-emerald-700). Light mode is untouched;
// an element that already declares its own `dark:` override for the same
// property keeps it.
//
// Re-run after adding new palette classes:  node scripts/gen-dark-palette.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const theme = readFileSync(join(root, "node_modules/tailwindcss/theme.css"), "utf8");
const pal = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (pal[m[1]] ??= {})[m[2]] = m[3].trim();

const HUES = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"];
const GRAYS = ["slate", "gray", "zinc", "neutral", "stone"];

const withAlpha = (c, op) => (op == null ? c : `color-mix(in oklab, ${c} ${op}%, transparent)`);
const tint = (hue, pct, op) => `color-mix(in oklab, ${pal[hue]["500"]} ${op == null ? pct : Math.round((pct * op) / 100)}%, transparent)`;

/** value for a utility in dark mode, or null to leave it alone */
function darkValue(prop, color, shade, op) {
  const s = Number(shade);
  const gray = GRAYS.includes(color);
  if (prop === "text") {
    if (s < 600) return null;
    if (gray) return withAlpha(s >= 800 ? "var(--foreground)" : "var(--muted-foreground)", op);
    return withAlpha(pal[color][s >= 700 ? "300" : "400"], op);
  }
  if (prop === "bg" || prop === "from" || prop === "via" || prop === "to") {
    if (s > 200) return null;
    if (gray) return withAlpha("var(--secondary)", op);
    return tint(color, { 50: 12, 100: 16, 200: 22 }[s], op);
  }
  if (prop === "border" || prop === "ring" || prop === "divide") {
    if (s > 300) return null;
    if (gray) return withAlpha("var(--border)", op);
    return tint(color, { 50: 22, 100: 28, 200: 34, 300: 42 }[s], op);
  }
  return null;
}

const CSS_PROP = {
  text: "color", bg: "background-color", border: "border-color", ring: "--tw-ring-color",
  from: "--tw-gradient-from", via: "--tw-gradient-via", to: "--tw-gradient-to",
};

// Collect every palette class (with optional variant + opacity) in src/.
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { if (f !== "test") walk(p); }
    else if (/\.(tsx?|jsx?)$/.test(f)) files.push(p);
  }
})(join(root, "src"));

const COLORS = [...HUES, ...GRAYS].join("|");
const re = new RegExp(`(?<![\\w:-])((?:hover|active|focus|group-hover|focus-visible):)?(text|bg|border|ring|from|via|to)-(${COLORS})-(\\d{2,3})(?:\\/(\\d{1,3}))?(?![\\w/-])`, "g");
const found = new Map();
for (const f of files) {
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(re)) found.set(m[0], m);
}

// Always cover the plain (no variant / no opacity) shades so new screens get
// sensible dark colours without re-running this script.
for (const color of [...HUES, ...GRAYS]) {
  for (const [prop, shades] of [["text", [600, 700, 800, 900, 950]], ["bg", [50, 100, 200]], ["border", [50, 100, 200, 300]]]) {
    for (const shade of shades) {
      const cls = `${prop}-${color}-${shade}`;
      if (!found.has(cls)) found.set(cls, [cls, undefined, prop, color, String(shade), undefined]);
    }
  }
}

const esc = (s) => s.replace(/[:/[\]]/g, (c) => `\\${c}`);
const pseudo = { hover: ":hover", active: ":active", focus: ":focus", "focus-visible": ":focus-visible" };
const rules = [];
for (const [cls, m] of [...found.entries()].sort()) {
  const [, variant, prop, color, shade, op] = m;
  if (!pal[color]?.[shade]) continue;
  const value = darkValue(prop, color, shade, op == null ? null : Number(op));
  if (!value) continue;
  const v = variant?.slice(0, -1);
  const own = prop === "from" || prop === "via" || prop === "to" ? "" : `:not([class*="dark:${prop}-"])`;
  const sel = v === "group-hover"
    ? `.dark .group:hover .${esc(cls)}${own}`
    : `.dark .${esc(cls)}${own}${v ? pseudo[v] : ""}`;
  rules.push(`${sel} { ${CSS_PROP[prop]}: ${value}; }`);
}

const out = `/* AUTO-GENERATED by scripts/gen-dark-palette.mjs — do not edit by hand. */
/* Dark-mode equivalents for hard-coded palette shades (${rules.length} rules). */
${rules.join("\n")}
`;
writeFileSync(join(root, "src/styles/dark-palette.css"), out);
console.log(`dark-palette.css: ${rules.length} rules`);
