#!/usr/bin/env node
/**
 * Writes src/lib/app-pulse/tz-places.ts from the IANA time-zone database the machine has
 * (zone.tab: each zone's country and its main city's coordinates; tzdata.zi: the old names that
 * point at it, like Asia/Calcutta for Asia/Kolkata). Run when the time-zone data changes:
 *
 *   node scripts/app-pulse/write-tz-places.mjs [/usr/share/zoneinfo]
 *
 * Generated, never hand-edited. Coordinates are kept to 0.1° (~11 km), the visit rule's limit.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] || "/usr/share/zoneinfo";
const out = join(process.cwd(), "src/lib/app-pulse/tz-places.ts");

/** ISO 6709 ±DDMM[SS]±DDDMM[SS] → degrees. */
function coords(s) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(s);
  if (!m) throw new Error(`bad coordinates ${s}`);
  const lat = (m[1] === "-" ? -1 : 1) * (Number(m[2]) + Number(m[3]) / 60 + Number(m[4] ?? 0) / 3600);
  const lng = (m[5] === "-" ? -1 : 1) * (Number(m[6]) + Number(m[7]) / 60 + Number(m[8] ?? 0) / 3600);
  return [Math.round(lat * 10) / 10, Math.round(lng * 10) / 10];
}

const zones = new Map();
for (const line of readFileSync(join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [country, c, tz] = line.split("\t");
  const [lat, lng] = coords(c);
  zones.set(tz, { country, lat, lng });
}

const links = [];
for (const line of readFileSync(join(dir, "tzdata.zi"), "utf8").split("\n")) {
  if (!line.startsWith("L ")) continue;
  const [, target, alias] = line.trim().split(/\s+/);
  if (zones.has(target) && !zones.has(alias)) links.push([alias, target]);
}

const zoneRows = [...zones.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([tz, z]) => `${tz},${z.country},${z.lat},${z.lng}`)
  .join(";");
const linkRows = links
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([alias, target]) => `${alias},${target}`)
  .join(";");

const src = `/**
 * Time zones and the main city each one is named for (generated by
 * scripts/app-pulse/write-tz-places.mjs from the IANA time-zone database; never hand-edit).
 * Server only: the visit recorder's way to put a country-only visit on the map.
 *
 * The host gives a visit's country from its internet address and nothing finer, so a visit is
 * placed at its device's time zone's main city (America/Winnipeg → Winnipeg, Manitoba) only when
 * that zone is in the same country; anything else stays a country with no point. A time zone is
 * coarser than a city and is already on every device's clock.
 */

const ZONES = ${JSON.stringify(zoneRows)};
const LINKS = ${JSON.stringify(linkRows)};

type ZonePlace = { country: string; lat: number; lng: number; city: string };

let table: Map<string, ZonePlace> | null = null;

function cityOf(tz: string): string {
  return (tz.split("/").pop() ?? tz).replace(/_/g, " ");
}

function load(): Map<string, ZonePlace> {
  if (table) return table;
  const t = new Map<string, ZonePlace>();
  for (const row of ZONES.split(";")) {
    const [tz, country, lat, lng] = row.split(",");
    t.set(tz, { country, lat: Number(lat), lng: Number(lng), city: cityOf(tz) });
  }
  for (const row of LINKS.split(";")) {
    const [alias, target] = row.split(",");
    const z = t.get(target);
    if (z) t.set(alias, z);
  }
  table = t;
  return t;
}

/**
 * The point for a visit from \`country\` (the host's, ISO 3166 alpha-2) on a device set to \`tz\`
 * (Intl's time zone): its zone's main city, rounded to 0.1°, only when the zone is in that country.
 */
export function zonePlace(tz: unknown, country: string | null): { city: string; lat: number; lng: number } | null {
  if (!country || typeof tz !== "string" || !tz || tz.length > 60) return null;
  const z = load().get(tz.trim());
  if (!z || z.country !== country.toUpperCase()) return null;
  return { city: z.city, lat: z.lat, lng: z.lng };
}

/** How many zones the table knows (for its test). */
export function zoneCount(): number {
  return load().size;
}
`;
writeFileSync(out, src);
console.log(`wrote ${out}: ${zones.size} zones, ${links.length} older names`);
